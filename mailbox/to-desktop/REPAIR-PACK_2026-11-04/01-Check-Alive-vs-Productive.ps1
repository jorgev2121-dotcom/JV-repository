# 01-Check-Alive-vs-Productive.ps1   READ-ONLY (GREEN). Writes ONE new report file. Changes nothing else.
# Question it answers: which automations are merely RUNNING, and which are actually PRODUCING output (RI-002).
$ErrorActionPreference = 'Continue'
$out = 'G:\My Drive\VTES-Outbox'
$stamp = Get-Date -Format 'yyyyMMdd-HHmm'
$rep = Join-Path $out ("DIAG-ALIVE-VS-PRODUCTIVE_" + $stamp + ".md")
$L = New-Object System.Collections.Generic.List[string]
$L.Add('# DIAG - alive vs productive  ' + (Get-Date -Format 'yyyy-MM-dd HH:mm') + ' ET')
$L.Add('Machine: ' + $env:COMPUTERNAME)
$boot = (Get-CimInstance Win32_OperatingSystem).LastBootUpTime
$L.Add('Up since: ' + $boot)
$L.Add('')
$L.Add('## Scheduled tasks (name, state, last run, last result)')
$tasks = Get-ScheduledTask | Where-Object { $_.TaskName -match 'CU-|VTES|Claude|Ollama|MasterAgent|Orchestr|Codex|Handover|Poller|Reconcil' }
foreach ($t in $tasks | Sort-Object TaskName) {
  $i = $null; try { $i = Get-ScheduledTaskInfo -TaskName $t.TaskName -TaskPath $t.TaskPath } catch {}
  $flag = ''
  if ($t.State -eq 'Disabled') { $flag = '  <== DISABLED' }
  elseif ($i -and $i.LastTaskResult -ne 0 -and $i.LastTaskResult -ne 267009 -and $i.LastTaskResult -ne 267011) { $flag = '  <== LAST RESULT NOT ZERO' }
  $L.Add(('- {0} | {1} | last {2} | result {3}{4}' -f $t.TaskName, $t.State, $(if($i){$i.LastRunTime}else{'?'}), $(if($i){$i.LastTaskResult}else{'?'}), $flag))
}
$L.Add('')
$L.Add('## Is the Outbox GROWING? (output files per window)')
foreach ($h in 1,3,12,24) {
  $n = @(Get-ChildItem $out -File -ErrorAction SilentlyContinue | Where-Object { $_.LastWriteTime -gt (Get-Date).AddHours(-$h) }).Count
  $L.Add(('- last {0} h: {1} files' -f $h, $n))
}
$L.Add('')
$L.Add('## Newest 8 receipts (EXECUTED / BLOCKER / BLOCKED)')
Get-ChildItem $out -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -match '^(EXECUTED|BLOCKER|BLOCKED)' } | Sort-Object LastWriteTime -Descending | Select-Object -First 8 | ForEach-Object { $L.Add(('- {0}  {1}' -f $_.LastWriteTime.ToString('MM-dd HH:mm'), $_.Name)) }
$L.Add('')
$L.Add('## Memory')
$os = Get-CimInstance Win32_OperatingSystem
$L.Add(('Free {0:N1} GB of {1:N1} GB' -f ($os.FreePhysicalMemory/1MB), ($os.TotalVisibleMemorySize/1MB)))
Get-Process | Sort-Object WorkingSet64 -Descending | Select-Object -First 12 | ForEach-Object { $L.Add(('- {0} pid {1}  {2:N0} MB' -f $_.ProcessName, $_.Id, ($_.WorkingSet64/1MB))) }
$L.Add('')
$L.Add('TRK-2026-10017 - generated by 01-Check-Alive-vs-Productive.ps1')
$L | Set-Content -Path $rep -Encoding UTF8
Write-Host ('WROTE ' + $rep)
