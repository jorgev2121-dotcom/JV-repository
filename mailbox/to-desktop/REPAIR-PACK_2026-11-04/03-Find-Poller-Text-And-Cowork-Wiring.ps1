# 03-Find-Poller-Text-And-Cowork-Wiring.ps1   READ-ONLY (GREEN). Writes ONE new report file.
# Finds (a) where the misleading "Most common cause ... not enough free memory" text lives, (b) how jobs name their MODEL,
# (c) where COWORK is listed as a required seat, (d) the two blocked job files.
$ErrorActionPreference = 'Continue'
$out = 'G:\My Drive\VTES-Outbox'
$stamp = Get-Date -Format 'yyyyMMdd-HHmm'
$rep = Join-Path $out ("DIAG-POLLER-AND-COWORK_" + $stamp + ".md")
$L = New-Object System.Collections.Generic.List[string]
$L.Add('# DIAG - poller error text, job format, Cowork wiring  ' + (Get-Date -Format 'yyyy-MM-dd HH:mm') + ' ET')
$roots = @('C:\Users\JV\OneDrive\Scripts','C:\Users\JV\OneDrive\Documents','G:\My Drive\VTES-Bridge') | Where-Object { Test-Path $_ }
function Find-Text($pattern, $title) {
  $L.Add(''); $L.Add('## ' + $title)
  $hits = 0
  foreach ($r in $roots) {
    Get-ChildItem $r -Recurse -File -Include *.ps1,*.psm1,*.json,*.cmd,*.bat,*.py -ErrorAction SilentlyContinue | Select-String -Pattern $pattern -ErrorAction SilentlyContinue | Select-Object -First 12 | ForEach-Object { $L.Add(('- {0}:{1}  {2}' -f $_.Path, $_.LineNumber, $_.Line.Trim())); $hits++ }
  }
  if ($hits -eq 0) { $L.Add('- no hits') }
}
Find-Text 'Most common cause on this machine' 'Where the generic memory excuse text is written'
Find-Text 'MODEL\s*:' 'How jobs and the poller handle a MODEL line'
Find-Text 'COWORK' 'Where COWORK is treated as a required seat'
$L.Add(''); $L.Add('## The two blocked job files (first 25 lines each)')
foreach ($pat in 'JOB-BACKLOG-01-LOCAL-DESKTOP-RETRY*','JOB-OCR-CATCHUP-FULL-COUNT*') {
  $f = Get-ChildItem 'G:\My Drive' -Recurse -File -Filter $pat -ErrorAction SilentlyContinue | Select-Object -First 1
  if ($f) { $L.Add('### ' + $f.FullName); $L.Add('```'); (Get-Content $f.FullName -TotalCount 25) | ForEach-Object { $L.Add($_) }; $L.Add('```') } else { $L.Add('### ' + $pat + ' : not found') }
}
$L.Add(''); $L.Add('TRK-2026-10017 - generated by 03-Find-Poller-Text-And-Cowork-Wiring.ps1')
$L | Set-Content -Path $rep -Encoding UTF8
Write-Host ('WROTE ' + $rep)
