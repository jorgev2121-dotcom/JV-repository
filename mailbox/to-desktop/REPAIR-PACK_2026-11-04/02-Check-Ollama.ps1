# 02-Check-Ollama.ps1   READ-ONLY (GREEN). Writes ONE new report file. Proves whether the LOCAL (Ollama) lane can answer.
$ErrorActionPreference = 'Continue'
$out = 'G:\My Drive\VTES-Outbox'
$stamp = Get-Date -Format 'yyyyMMdd-HHmm'
$rep = Join-Path $out ("DIAG-OLLAMA_" + $stamp + ".md")
$L = New-Object System.Collections.Generic.List[string]
$L.Add('# DIAG - Ollama / LOCAL lane  ' + (Get-Date -Format 'yyyy-MM-dd HH:mm') + ' ET')
$os = Get-CimInstance Win32_OperatingSystem
$free = [math]::Round($os.FreePhysicalMemory/1MB,1)
$L.Add(('Free RAM before tests: {0} GB of {1} GB' -f $free, [math]::Round($os.TotalVisibleMemorySize/1MB,1)))
$L.Add('Claude/node/codex/ollama processes: ' + (@(Get-Process -ErrorAction SilentlyContinue | Where-Object { $_.ProcessName -match 'claude|node|codex|ollama' }).Count))
$L.Add('')
$L.Add('## Ollama settings seen')
foreach ($n in 'OLLAMA_KEEP_ALIVE','OLLAMA_MAX_LOADED_MODELS','OLLAMA_NUM_PARALLEL','OLLAMA_HOST','OLLAMA_MODELS') {
  $u = [Environment]::GetEnvironmentVariable($n,'User'); $m = [Environment]::GetEnvironmentVariable($n,'Machine')
  $L.Add(('- {0}: user=[{1}] machine=[{2}]' -f $n,$u,$m))
}
$L.Add('')
$L.Add('## ollama list / ps')
try { $L.Add((& ollama list 2>&1 | Out-String)) } catch { $L.Add('ollama list failed: ' + $_.Exception.Message) }
try { $L.Add((& ollama ps 2>&1 | Out-String)) } catch { $L.Add('ollama ps failed: ' + $_.Exception.Message) }
$L.Add('')
$L.Add('## API reachable?')
$models = @()
try { $tags = Invoke-RestMethod -Uri 'http://localhost:11434/api/tags' -TimeoutSec 10; $models = @($tags.models | ForEach-Object { $_.name }); $L.Add('YES. Models: ' + ($models -join ', ')) } catch { $L.Add('NO. ' + $_.Exception.Message) }
$L.Add('')
$L.Add('## One-line answer test per model (120 s limit each)')
foreach ($m in $models | Select-Object -First 4) {
  $sw = [Diagnostics.Stopwatch]::StartNew()
  try {
    $body = @{ model = $m; prompt = 'Reply with the single word OK'; stream = $false } | ConvertTo-Json
    $r = Invoke-RestMethod -Uri 'http://localhost:11434/api/generate' -Method Post -Body $body -ContentType 'application/json' -TimeoutSec 120
    $L.Add(('- {0}: ANSWERED in {1:N1} s -> [{2}]' -f $m, $sw.Elapsed.TotalSeconds, ($r.response.Trim())))
  } catch { $L.Add(('- {0}: FAILED after {1:N1} s -> {2}' -f $m, $sw.Elapsed.TotalSeconds, $_.Exception.Message)) }
}
$L.Add('')
$L.Add('## Model name that failed with 404 on 2026-11-03 16:15 ET')
$bad = 'claude-sonnet-5'
$L.Add(('Is [{0}] an installed Ollama model? {1}' -f $bad, $(if ($models -contains $bad) {'YES'} else {'NO - a Claude model name cannot run on the LOCAL lane; that job was mis-routed'})))
$L.Add('')
$L.Add('TRK-2026-10017 - generated by 02-Check-Ollama.ps1')
$L | Set-Content -Path $rep -Encoding UTF8
Write-Host ('WROTE ' + $rep)
