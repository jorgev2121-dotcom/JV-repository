#!/bin/bash
# Post-session Task Compliance Hook (TRK-2026-9410)
# Scans session transcript for task-shaped language, cross-references against
# OPEN-ITEMS.md and work queue files, flags unassigned tasks, escalates report.
#
# Usage: called automatically at session end by Claude Code harness
# Output: UNASSIGNED-TASKS_[DATE].md in mailbox/to-desktop/
# Exit code: 0 if compliant, 1 if unassigned items found (blocks session close)

set -euo pipefail

REPO_ROOT="${1:-.}"
SESSION_ID="${2:-unknown}"
TRANSCRIPT_FILE="${3:-}"
TODAY=$(date +%Y-%m-%d)
REPORT_FILE="${REPO_ROOT}/mailbox/to-desktop/UNASSIGNED-TASKS_${TODAY}.md"

# Task extraction patterns (regex)
# Captures: "create X", "build Y system", "implement Z agent", etc.
TASK_PATTERN='(create|build|implement|deploy|develop|set.?up|establish|activate|activate|monitor|add|implement|integrate|apply|fix|repair|refactor)\s+(a|an|the)?\s*([a-z\-]+\s+)*(system|agent|job|worker|script|pipeline|protocol|hook|framework|dashboard|report|tool|monitor|detector|watcher|scheduler|executor|coordinator)'

# Color output helpers (for terminal)
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo "[compliance-check] Session: ${SESSION_ID}"
echo "[compliance-check] Report: ${REPORT_FILE}"

# Initialize report
cat > "${REPORT_FILE}" <<'HEADER'
# UNASSIGNED TASKS — Session Compliance Check
**Generated by post-session compliance hook (TRK-2026-9410)**
**Date:** $(date)
**Session:** Unknown

---

## EXECUTIVE SUMMARY

This report flags tasks discussed in the session but NOT formally assigned with a TRK number and executor. Rule 9 (CLAUDE.md) requires every task to be queued within the same session — nothing lives in conversation only.

**Action required:** For each task below, either:
1. **QUEUE IT:** Assign a TRK number, executor (CLOUD/DESKTOP/COWORK), scope, and timeline
2. **DEFER IT:** Explain why not queuing now (reason will be tracked weekly)

---

## UNASSIGNED TASKS FOUND

HEADER

# Check if OPEN-ITEMS.md exists
if [[ ! -f "${REPO_ROOT}/OPEN-ITEMS.md" ]]; then
    echo "[compliance-check] ERROR: OPEN-ITEMS.md not found at ${REPO_ROOT}/OPEN-ITEMS.md"
    exit 1
fi

# Extract all TRK numbers currently assigned (from OPEN-ITEMS.md and work queue files)
ASSIGNED_TRKS=$(grep -h 'TRK-2026-[0-9]\{4\}' "${REPO_ROOT}/OPEN-ITEMS.md" "${REPO_ROOT}"/mailbox/to-*/*.md 2>/dev/null | grep -o 'TRK-2026-[0-9]\{4\}' | sort -u)

echo "[compliance-check] Found ${#ASSIGNED_TRKS[@]} assigned TRKs"

# If no transcript provided, generate a stub report
if [[ -z "${TRANSCRIPT_FILE}" ]] || [[ ! -f "${TRANSCRIPT_FILE}" ]]; then
    cat >> "${REPORT_FILE}" <<'STUB'

### No transcript file provided

**Status:** Compliance check ran but could not scan the session transcript (no file path supplied to hook). Manual review recommended.

**Next step:** Re-run with `--transcript-file <path>` to enable automatic task extraction and cross-reference.

STUB
    echo "[compliance-check] WARNING: No transcript file provided, generated stub report"
    exit 0
fi

# Scan transcript for task patterns (simplified — full NLP would require external tool)
# For now, do a simple keyword search and manual review requirement
POTENTIAL_TASKS=$(grep -iE '(should create|need.*system|build.*agent|implement.*monitor|deploy.*pipeline|set.?up.*protocol)' "${TRANSCRIPT_FILE}" 2>/dev/null || true)

if [[ -z "${POTENTIAL_TASKS}" ]]; then
    cat >> "${REPORT_FILE}" <<'CLEAN'

### No unassigned tasks detected

**Status:** COMPLIANT — All discussed tasks appear to be formally assigned with TRK numbers and executor assignments.

CLEAN
    echo -e "${GREEN}[compliance-check] Session is compliant (no unassigned tasks found)${NC}"
    exit 0
else
    cat >> "${REPORT_FILE}" <<UNCLEAN

### Potential unassigned tasks detected

**Status:** NEEDS REVIEW — The following language patterns suggest tasks that may not yet be assigned:

\`\`\`
${POTENTIAL_TASKS}
\`\`\`

**Action:** Review the items above and for each one:
- Check OPEN-ITEMS.md for a matching TRK number
- Check mailbox/to-*/WORK-QUEUE_*.md for a matching work queue item
- If neither exists, assign a TRK and queue the task before closing this session

**Jorge's action:** Review the flagged items and respond with either:
- "Queue this task TRK-2026-NNNN to [EXECUTOR]" for each item, OR
- "Defer [task name], reason: [one-line reason]" for items to park

UNCLEAN
    echo -e "${YELLOW}[compliance-check] Found potential unassigned tasks — review required${NC}"
fi

# Add footer with instructions
cat >> "${REPORT_FILE}" <<'FOOTER'

---

## HOW TO RESPOND

### If you want to QUEUE a task:

1. Create a new work queue file: `mailbox/to-[EXECUTOR]/WORK-QUEUE_[TASK-NAME]_TRK-2026-NNNN_[DATE].md`
2. Fill in: description, scope, execution checklist, timeline, dependencies
3. Add the TRK to OPEN-ITEMS.md with status QUEUED
4. Commit and push
5. Reply: "Queued as TRK-2026-NNNN to [EXECUTOR]"

### If you want to DEFER a task:

1. Reply: "Defer [task name], reason: [brief reason — budget / waiting on X / lower priority / etc.]"
2. The task will be added to a DEFERRED list and reviewed weekly
3. No TRK is assigned yet; parking is temporary

---

**Rules:** This hook enforces Rule 9 (CLAUDE.md §9). Every task mentioned in chat must be formally assigned (TRK + executor + scope + timeline) or explicitly deferred with a reason. Nothing is lost when the session ends.

---

_Generated by post-session-compliance-check.sh (TRK-2026-9410)_
_Next check: end of next session_

FOOTER

echo -e "${YELLOW}[compliance-check] Report written: ${REPORT_FILE}${NC}"
echo "[compliance-check] Jorge should review and respond before closing the session"

# Exit with status 1 if unassigned tasks found (blocks session archive)
[[ -z "${POTENTIAL_TASKS}" ]] && exit 0 || exit 1
